"""LLM-as-a-judge evaluation.

Covers FR-004, TM-04, ADR-003.

The judge evaluates model answers against reference answers using:
- Score (1-5)
- Binary flags (hallucination, wrong_citation, incorrect_refusal)
- Rationale (chain-of-thought explanation)

Uses repair-retry strategy for invalid JSON responses (ADR-003).
"""

from __future__ import annotations

import json
import logging
import time
from typing import Any

from regulated_eval.adapters.base import BaseAdapter, LLMRequest, LLMResponse
from regulated_eval.config import Config
from regulated_eval.exceptions import RateLimitExhausted
from regulated_eval.observability import get_tracer
from regulated_eval.schemas import GoldenRecord, JudgeResult

logger = logging.getLogger(__name__)

# Judge prompt template (v1)
JUDGE_PROMPT_TEMPLATE = """You are an expert evaluator for a regulated LLM evaluation framework.
Your task is to evaluate the model's answer against the reference answer for a tax/accounting question.

## Question
{question}

## Reference Answer
{reference_answer}

## Model Answer
{model_answer}

## Citations
{citations}

## Evaluation Criteria
1. **Factual Accuracy**: Does the model answer correctly address the question?
2. **Citation Accuracy**: Are the citations (НК РФ articles) correct and relevant?
3. **Hallucination**: Does the model make up facts, articles, or numbers not in the reference?
4. **Refusal Correctness**: If the reference answer indicates a refusal was appropriate, was the model's refusal correct?

## Output Format
Return a JSON object with the following fields:
- "score": integer 1-5 (1=poor, 2=fair, 3=good, 4=very good, 5=excellent)
- "hallucination": boolean (true if the answer contains hallucinations)
- "wrong_citation": boolean (true if citations are incorrect)
- "incorrect_refusal": boolean (true if refusal was incorrect)
- "rationale": string explaining your evaluation (max 2000 chars)

## Example Output
{{
  "score": 4,
  "hallucination": false,
  "wrong_citation": false,
  "incorrect_refusal": false,
  "rationale": "The model correctly identified that USN exempts from VAT. The citation to NK RF Art. 346.11 is correct. Minor improvement: could have mentioned the exception for VAT on exports."
}}

Evaluate the model answer and return ONLY the JSON object.
"""


class Judge:
    """LLM-as-a-judge evaluator.

    Uses a separate LLM call to evaluate model answers against reference answers.
    Supports repair-retry for invalid JSON responses.
    """

    def __init__(
        self,
        adapter: BaseAdapter,
        config: Config | None = None,
        prompt_version: str = "v1",
    ) -> None:
        """Initialize judge.

        Args:
            adapter: LLM adapter for judge calls.
            config: Optional Config object.
            prompt_version: Version of the judge prompt template.
        """
        self._adapter = adapter
        self._config = config or Config()
        self._prompt_version = prompt_version

    def evaluate(
        self,
        record: GoldenRecord,
        model_answer: str,
        trace_id: str = "",
    ) -> JudgeResult:
        """Evaluate a model answer against the reference.

        Args:
            record: Golden set record with question and reference.
            model_answer: Answer generated by the model.
            trace_id: W3C trace-id for correlation.

        Returns:
            JudgeResult with score, flags, and rationale.
        """
        start_time = time.monotonic()
        tracer = get_tracer("regulated-eval")

        span = None
        if tracer is not None:
            span = tracer.start_span("judge.evaluate")
            span.set_attribute("record.id", record.id)
            span.set_attribute("judge.model", self._adapter.model_name())
            span.set_attribute("judge.prompt_version", self._prompt_version)

        prompt = self._build_prompt(record, model_answer)

        request = LLMRequest(
            prompt=prompt,
            model=self._adapter.model_name(),
            temperature=0.0,  # Deterministic evaluation
            max_tokens=1024,
            metadata={
                "trace_id": trace_id,
                "record_id": record.id,
                "role": "judge",
            },
        )

        response = self._adapter.generate_sync(request)

        if response.error:
            logger.warning("Judge error for record %s: %s", record.id, response.error)
            if span is not None:
                span.set_attribute("judge.status", "error")
                span.end()
            return JudgeResult(
                record_id=record.id,
                score=0,
                hallucination=False,
                wrong_citation=False,
                incorrect_refusal=False,
                rationale=f"Judge error: {response.error}",
                judge_model=self._adapter.model_name(),
                judge_prompt_version=self._prompt_version,
                judge_status="parse_error",
                trace_id=trace_id,
            )

        # Parse JSON response with repair-retry
        result = self._parse_response(response.text, record.id, trace_id)

        # Record span attributes
        if span is not None:
            span.set_attribute("judge.score", result.score)
            span.set_attribute("judge.hallucination", result.hallucination)
            span.set_attribute("judge.wrong_citation", result.wrong_citation)
            span.set_attribute("judge.incorrect_refusal", result.incorrect_refusal)
            span.set_attribute("judge.status", result.judge_status)

            duration = time.monotonic() - start_time
            span.set_attribute("judge.duration_ms", duration * 1000)
            span.end()

        return result

    def _build_prompt(self, record: GoldenRecord, model_answer: str) -> str:
        """Build the judge prompt."""
        citations = "\n".join(f"- {c}" for c in record.citations) if record.citations else "Не указаны"
        return JUDGE_PROMPT_TEMPLATE.format(
            question=record.question,
            reference_answer=record.reference_answer,
            model_answer=model_answer,
            citations=citations,
        )

    def _parse_response(
        self,
        text: str,
        record_id: str,
        trace_id: str,
        attempt: int = 0,
        max_attempts: int = 2,
    ) -> JudgeResult:
        """Parse judge response with repair-retry.

        Args:
            text: Raw response text from LLM.
            record_id: Record ID for logging.
            trace_id: Trace ID for correlation.
            attempt: Current attempt number.
            max_attempts: Maximum retry attempts.

        Returns:
            JudgeResult.
        """
        try:
            # Extract JSON from response (handle markdown code blocks)
            text = text.strip()
            if "```" in text:
                # Extract JSON from code block
                start = text.find("{")
                end = text.rfind("}") + 1
                if start >= 0 and end > start:
                    text = text[start:end]

            data = json.loads(text)
            result = JudgeResult(
                record_id=record_id,
                score=data.get("score", 0),
                hallucination=bool(data.get("hallucination", False)),
                wrong_citation=bool(data.get("wrong_citation", False)),
                incorrect_refusal=bool(data.get("incorrect_refusal", False)),
                rationale=str(data.get("rationale", "")),
                judge_model=self._adapter.model_name(),
                judge_prompt_version=self._prompt_version,
                judge_status="ok",
                trace_id=trace_id,
            )
            return result

        except (json.JSONDecodeError, KeyError, TypeError) as e:
            if attempt < max_attempts:
                logger.warning(
                    "Judge parse error for record %s (attempt %d/%d): %s",
                    record_id,
                    attempt + 1,
                    max_attempts,
                    e,
                )
                # Retry with repair prompt
                repair_prompt = (
                    f"Your previous response was invalid JSON. "
                    f"Please return ONLY a valid JSON object with fields: "
                    f"score (int 1-5), hallucination (bool), wrong_citation (bool), "
                    f"incorrect_refusal (bool), rationale (string).\n\n"
                    f"Original response: {text[:500]}"
                )
                request = LLMRequest(
                    prompt=repair_prompt,
                    model=self._adapter.model_name(),
                    temperature=0.0,
                    max_tokens=1024,
                )
                response = self._adapter.generate_sync(request)
                return self._parse_response(
                    response.text, record_id, trace_id, attempt + 1, max_attempts
                )
            else:
                logger.error(
                    "Judge parse failed for record %s after %d attempts: %s",
                    record_id,
                    max_attempts,
                    e,
                )
                return JudgeResult(
                    record_id=record_id,
                    score=0,
                    hallucination=False,
                    wrong_citation=False,
                    incorrect_refusal=False,
                    rationale=f"Parse error after {max_attempts} attempts: {e}",
                    judge_model=self._adapter.model_name(),
                    judge_prompt_version=self._prompt_version,
                    judge_status="parse_error",
                    trace_id=trace_id,
                )
